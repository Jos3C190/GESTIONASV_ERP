from __future__ import annotations

import uuid
from typing import Any, Protocol


class InventoryAdjustmentRepository(Protocol):
    async def list_options(self, **kwargs: Any) -> dict[str, Any]: ...
    async def list_adjustments(self, **kwargs: Any) -> tuple[list[dict[str, Any]], int]: ...
    async def get_adjustment(self, company_id: uuid.UUID, adjustment_id: uuid.UUID) -> dict[str, Any] | None: ...
    async def create_adjustment(self, **kwargs: Any) -> dict[str, Any]: ...
    async def update_adjustment(self, **kwargs: Any) -> dict[str, Any]: ...
    async def approve_adjustment(self, **kwargs: Any) -> dict[str, Any]: ...
    async def cancel_adjustment(self, **kwargs: Any) -> dict[str, Any]: ...
    async def apply_adjustment(self, **kwargs: Any) -> dict[str, Any]: ...
    async def create_correction(self, **kwargs: Any) -> dict[str, Any]: ...
